-- SPIELTAG 8 (letzter Spieltag der regulären Saison) + 2 Korrekturen der Icon League.
-- Komplett im Supabase SQL Editor ausführen ("Run without RLS").
-- Spieltagswerte direkt pro Spiel (TIL_S5_M00043-M00048).

-- Korrekturen: Die Icon League hat zwei Gelbe Karten nachträglich gestrichen (+2 Punkte je Spieler)
--   Haydar Bayram (The Pack): Spieltag 4
--   Liridon Krasniqi (Two Stripes): Spieltag 6
update player_round_statistics prs set value = 0, status = 'corrected'
from fantasy_rounds r, seasons s, season_players sp, players p
where r.id = prs.round_id and s.id = r.season_id and s.slug = 'season-5'
  and sp.id = prs.season_player_id and p.id = sp.player_id and prs.stat_key = 'yellow'
  and ((p.external_refs->>'icon_slug' = 'haydar-bayram' and r.number = 4)
    or (p.external_refs->>'icon_slug' = 'liridon-krasniqi' and r.number = 6));

select r.number as spieltag_neu_berechnet, compute_round(r.id, true) as ergebnis
from fantasy_rounds r join seasons s on s.id = r.season_id
where s.slug = 'season-5' and r.number in (4, 6) order by r.number;

